#!/usr/bin/env python3
"""Keep the CloudFront origin-facing IP ranges in EnvironmentInfo_Ext.cs up to date.

AWS publishes the authoritative list at https://ip-ranges.amazonaws.com/ip-ranges.json.
This script filters it down to the CLOUDFRONT_ORIGIN_FACING service, sorts and
de-duplicates the prefixes, and rewrites the generated block inside a C# file.

The block is delimited by the markers ``// <cloudfront-ranges>`` and
``// </cloudfront-ranges>``.  Everything between them, inclusive, is replaced.
The generated code is indented to match the leading whitespace of the opening
marker line in the target file, so the block stays inside its namespace.

Only the standard library is used.
"""

import argparse
import http.client
import ipaddress
import json
import os
import sys
import urllib.request

AWS_URL = "https://ip-ranges.amazonaws.com/ip-ranges.json"
SERVICE = "CLOUDFRONT_ORIGIN_FACING"
OPEN_MARKER = "// <cloudfront-ranges>"
CLOSE_MARKER = "// </cloudfront-ranges>"


def load_ranges(path):
    """Return (sync_token, create_date, prefixes) for the CLOUDFRONT service.

    ``prefixes`` is a de-duplicated, ipaddress-ordered list: IPv4 first, then
    IPv6.  ``path`` is either a local file or, when it is None, the AWS URL.
    """
    if path is None:
        with urllib.request.urlopen(AWS_URL, timeout=30) as response:
            data = json.load(response)
    else:
        with open(path, "rb") as handle:
            data = json.load(handle)

    sync_token = str(data.get("syncToken", ""))
    create_date = str(data.get("createDate", ""))

    ipv4 = [
        ipaddress.ip_network(p["ip_prefix"], strict=False)
        for p in data.get("prefixes", [])
        if p.get("service") == SERVICE
    ]
    ipv6 = [
        ipaddress.ip_network(p["ipv6_prefix"], strict=False)
        for p in data.get("ipv6_prefixes", [])
        if p.get("service") == SERVICE
    ]

    # Sort by network address, then de-duplicate.  ip_network objects compare by
    # (network address, prefix length), which gives a stable, canonical order.
    ipv4 = sorted(set(ipv4))
    ipv6 = sorted(set(ipv6))

    prefixes = [str(n) for n in ipv4] + [str(n) for n in ipv6]
    return sync_token, create_date, prefixes, len(ipv4), len(ipv6)


def build_block(sync_token, create_date, prefixes, indent=""):
    """Render the generated block as a list of lines (no line endings).

    Every returned line is already indented, so the caller can join them with
    the target file's line ending without any line losing its indentation.
    """
    prefix_lines = []
    for index, prefix in enumerate(prefixes):
        comma = "" if index == len(prefixes) - 1 else ","
        prefix_lines.append("\t\t\t\"%s\"%s" % (prefix, comma))

    lines = [
        "// <cloudfront-ranges>",
        "// Generated by scripts/update-cloudfront-ranges.py from "
        "https://ip-ranges.amazonaws.com/ip-ranges.json",
        "// (service CLOUDFRONT_ORIGIN_FACING). Do not edit by hand.",
        "internal static class CloudFrontRanges {",
        "\tpublic const string SyncToken = \"%s\";" % sync_token,
        "\tpublic const string CreateDate = \"%s\";" % create_date,
        "\tpublic static readonly string[] Prefixes = new string[] {",
    ]
    lines.extend(prefix_lines)
    lines.extend(["\t};", "}", "// </cloudfront-ranges>"])

    # Indent every line so the block sits inside the target file's namespace.
    return [indent + line for line in lines]


def parse_block(block_lines):
    """Extract the prefix list from a generated block, ignoring the metadata.

    Returns the list of prefix strings (without quotes or commas).
    """
    prefixes = []
    for line in block_lines:
        stripped = line.strip()
        if not stripped.startswith('"'):
            continue
        # Drop a trailing comma, then strip the surrounding quotes.
        value = stripped.rstrip(",")
        if len(value) >= 2 and value[0] == '"' and value[-1] == '"':
            prefixes.append(value[1:-1])
        elif len(value) >= 1 and value[0] == '"':
            # A line that opens a quote but has no closing quote is malformed;
            # skip it rather than emitting a bad prefix.
            continue
    return prefixes


def read_lines(path):
    """Read a file and return (lines, newline).

    ``lines`` are split on the detected newline and have it stripped, so they
    contain no line-ending characters.  ``newline`` is the file's line ending
    (``"\r\n"`` or ``"\n"``), or ``"\n"`` when the file is empty.
    """
    with open(path, "rb") as handle:
        raw = handle.read()
    if b"\r\n" in raw:
        newline = "\r\n"
    else:
        newline = "\n"
    text = raw.decode("utf-8")
    lines = text.split(newline)
    # A trailing newline leaves an empty final element; drop it so the list
    # mirrors the file's logical lines.
    if lines and lines[-1] == "":
        lines.pop()
    return lines, newline


def find_markers(lines):
    """Return (open_index, close_index) or None.

    Raises ValueError when a marker is missing or appears more than once.
    """
    open_positions = [i for i, line in enumerate(lines) if line.strip() == OPEN_MARKER]
    close_positions = [i for i, line in enumerate(lines) if line.strip() == CLOSE_MARKER]

    if len(open_positions) != 1:
        raise ValueError(
            "expected exactly one '%s' marker, found %d" % (OPEN_MARKER, len(open_positions))
        )
    if len(close_positions) != 1:
        raise ValueError(
            "expected exactly one '%s' marker, found %d" % (CLOSE_MARKER, len(close_positions))
        )

    open_index = open_positions[0]
    close_index = close_positions[0]
    if close_index < open_index:
        raise ValueError("'%s' appears before '%s'" % (CLOSE_MARKER, OPEN_MARKER))
    return open_index, close_index


def detect_indent(lines, open_index):
    """Return the leading whitespace of the opening marker line."""
    line = lines[open_index]
    return line[: len(line) - len(line.lstrip())]


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Update the CloudFront origin-facing ranges in a C# file."
    )
    parser.add_argument(
        "--input",
        default=None,
        help="Local ip-ranges.json path. Defaults to the AWS URL.",
    )
    parser.add_argument(
        "--target",
        default=None,
        help="C# file to update. Defaults to Source/NET/EnvironmentInfo_Ext.cs.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Never write. Exit 1 when the ranges differ, printing the diff.",
    )
    parser.add_argument(
        "--print",
        action="store_true",
        help="Write the generated block to stdout and exit.",
    )
    args = parser.parse_args(argv)

    # Exit 1 is reserved for --check finding a difference. A feed that can't be read
    # (network, HTTP, JSON or an unexpected shape) exits 2, so it is never taken for a
    # range change.
    try:
        sync_token, create_date, prefixes, n_ipv4, n_ipv6 = load_ranges(args.input)
    except (OSError, http.client.HTTPException, ValueError, KeyError, AttributeError, TypeError) as exc:
        reason = "missing key %s" % exc if isinstance(exc, KeyError) else str(exc)
        sys.stderr.write("error: cannot read the IP ranges: %s\n" % reason)
        return 2

    # A list without IPv4 or without IPv6 would stop GetClientIPAddress from trusting
    # CloudFront for that family, so a truncated or reshaped feed is an error.
    if n_ipv4 == 0 or n_ipv6 == 0:
        sys.stderr.write(
            "error: expected both IPv4 and IPv6 %s ranges; nothing was written\n" % SERVICE
        )
        return 2

    # Resolve the target path relative to the repo root (parent of scripts/).
    if args.target is None:
        repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        target_path = os.path.join(repo_root, "Source", "NET", "EnvironmentInfo_Ext.cs")
    else:
        target_path = args.target

    # --print: emit the block to stdout.  When the target is missing, use no
    # indentation.
    if args.print:
        indent = ""
        if os.path.exists(target_path):
            try:
                lines, _ = read_lines(target_path)
                open_index, _ = find_markers(lines)
                indent = detect_indent(lines, open_index)
            except (ValueError, OSError):
                indent = ""
        block = build_block(sync_token, create_date, prefixes, indent)
        sys.stdout.write("\n".join(block) + "\n")
        return 0

    # Read the target file (binary, preserving its line endings).
    try:
        lines, newline = read_lines(target_path)
    except FileNotFoundError:
        sys.stderr.write("error: target file not found: %s\n" % target_path)
        return 2

    try:
        open_index, close_index = find_markers(lines)
    except ValueError as exc:
        sys.stderr.write("error: %s\n" % exc)
        return 2

    indent = detect_indent(lines, open_index)
    new_block = build_block(sync_token, create_date, prefixes, indent)

    # Compare ignoring SyncToken and CreateDate: only the prefix list matters.
    old_block = lines[open_index : close_index + 1]
    old_prefixes = parse_block(old_block)
    changed = old_prefixes != prefixes

    if args.check:
        if not changed:
            print("CloudFront ranges unchanged (%d IPv4, %d IPv6)" % (n_ipv4, n_ipv6))
            return 0
        added = [p for p in prefixes if p not in set(old_prefixes)]
        removed = [p for p in old_prefixes if p not in set(prefixes)]
        print("CloudFront ranges differ (%d IPv4, %d IPv6):" % (n_ipv4, n_ipv6))
        for p in added:
            print("  + %s" % p)
        for p in removed:
            print("  - %s" % p)
        return 1

    if not changed:
        print("CloudFront ranges unchanged (%d IPv4, %d IPv6)" % (n_ipv4, n_ipv6))
        return 0

    # Splice the new block in place of the old one.
    new_lines = lines[:open_index] + new_block + lines[close_index + 1 :]
    output = newline.join(new_lines)
    if output and not output.endswith(newline):
        output += newline
    with open(target_path, "wb") as handle:
        handle.write(output.encode("utf-8"))

    added = [p for p in prefixes if p not in set(old_prefixes)]
    removed = [p for p in old_prefixes if p not in set(prefixes)]
    print("CloudFront ranges updated: +%d -%d" % (len(added), len(removed)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
