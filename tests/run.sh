#!/usr/bin/env bash
# Extracts the pure ClientIpResolver / CloudFrontRanges regions from the production
# source and runs the dotnet test project against them.
#
# Usage: tests/run.sh [source-file]
#   default source: Source/NET/EnvironmentInfo_Ext.cs (relative to the repo root)
#   relative source paths are resolved from the current directory.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
PROJECT="$ROOT/tests/ClientIpResolver.Tests"
OUT="$PROJECT/obj/Extracted.g.cs"

if [[ $# -ge 1 ]]; then
	SRC="$1"
else
	SRC="$ROOT/Source/NET/EnvironmentInfo_Ext.cs"
fi

if [[ ! -f "$SRC" ]]; then
	echo "ERROR: source file not found: $SRC" >&2
	exit 1
fi

# Prints the region between the start and end marker lines (markers included).
# Marker lines are matched after trimming surrounding whitespace.
extract_region() {
	local start="$1" end="$2"
	awk -v s="$start" -v e="$end" '
		{
			l = $0
			sub(/^[ \t]+/, "", l)
			sub(/[ \t\r]+$/, "", l)
		}
		l == s { f = 1 }
		f { print }
		l == e && f { f = 0; done = 1 }
		END { if (!done) exit 1 }
	' "$SRC"
}

RESOLVER="$(extract_region "// <client-ip-resolver>" "// </client-ip-resolver>")" || {
	echo "ERROR: region '// <client-ip-resolver>' ... '// </client-ip-resolver>' not found in $SRC" >&2
	exit 1
}
RANGES="$(extract_region "// <cloudfront-ranges>" "// </cloudfront-ranges>")" || {
	echo "ERROR: region '// <cloudfront-ranges>' ... '// </cloudfront-ranges>' not found in $SRC" >&2
	exit 1
}

mkdir -p "$PROJECT/obj"
{
	echo "// Generated by tests/run.sh from: $SRC"
	echo "namespace OutSystems.NssEnvironmentInfo_Ext {"
	printf '%s\n' "$RESOLVER"
	echo
	printf '%s\n' "$RANGES"
	echo "}"
} > "$OUT"

# Locate dotnet: $DOTNET, then PATH, then ~/.dotnet/dotnet.
if [[ -n "${DOTNET:-}" ]]; then
	DOTNET_BIN="$DOTNET"
elif command -v dotnet >/dev/null 2>&1; then
	DOTNET_BIN="$(command -v dotnet)"
elif [[ -x "$HOME/.dotnet/dotnet" ]]; then
	DOTNET_BIN="$HOME/.dotnet/dotnet"
else
	echo "ERROR: dotnet not found (set DOTNET, add it to PATH, or install to ~/.dotnet)" >&2
	exit 1
fi

echo "Source:  $SRC"
echo "Extract: $OUT"
echo "dotnet:  $DOTNET_BIN"
echo

cd "$ROOT"
"$DOTNET_BIN" run --project tests/ClientIpResolver.Tests
